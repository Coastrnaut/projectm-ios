APP_SOURCE = "https://github.com/Coastrnaut/projectm-ios"


def engine_commit() -> str:
    """The pinned engine commit, from ADR-0004."""
    text = (ROOT / "docs/adr/0004-dependency-pinning.md").read_text(encoding="utf-8")
    match = re.search(r"Currently `([0-9a-f]{40})`", text)
    if not match:
        sys.exit("ADR-0004 has no 'Currently `<commit>`' pin for libprojectM")
    return match.group(1)


def header_comment(path: Path, last_line: str) -> str:
    """The leading comment block of a source file, up to and including `last_line`."""
    lines = path.read_text(encoding="utf-8", errors="replace").splitlines()
    end = next(i for i, line in enumerate(lines) if last_line in line)
    return "\n".join(lines[: end + 1]) + "\n"


def stb_license() -> str:
    path = next(ENGINE.glob("**/stb_image.h"))
    text = path.read_text(encoding="utf-8", errors="replace")
    start = text.index("This software is available under 2 licenses")
    end = text.index("*/", start)
    return text[start:end].rstrip() + "\n"


