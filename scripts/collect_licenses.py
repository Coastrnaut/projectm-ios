def generate() -> None:
    OUT.mkdir(parents=True, exist_ok=True)
    manifest = []
    for item in components() + pack_components(pack_manifest()):
        text = item.pop("text", None)
        source = item.pop("source", None)
        if text is None:
            if not source.exists():
                sys.exit(f"missing license source {source.relative_to(ROOT)} "
                         "(engine submodule checked out? ANGLE built with build_angle_xcframework.py?)")
            text = source.read_text(encoding="utf-8", errors="replace")
        file = f"{item['id']}.txt"
        (OUT / file).write_text(text.replace("\r\n", "\n"), encoding="utf-8")
        manifest.append({"version": "", **item, "file": file})
    commit = engine_commit()
    note = {"title": "libprojectM source and replacement (LGPL-2.1)",
            "text": LGPL_NOTE.format(engine=ENGINE_SOURCE, commit=commit, app=APP_SOURCE)}
    (OUT / "licenses.json").write_text(
        json.dumps({"components": manifest, "lgplNote": note}, indent=2, ensure_ascii=False) + "\n", encoding="utf-8")
    print(f"wrote {len(manifest)} components to {OUT.relative_to(ROOT)}")


def check() -> int:
    """The committed manifest names every file, every file is non-empty, and the pin matches ADR-0004."""
    manifest_path = OUT / "licenses.json"
    if not manifest_path.exists():
        print(f"missing {manifest_path.relative_to(ROOT)}")
        return 1
    data = json.loads(manifest_path.read_text(encoding="utf-8"))
    problems = []
    for item in data["components"]:
        path = OUT / item["file"]
        if not path.exists() or not path.read_text(encoding="utf-8").strip():
            problems.append(f"{item['id']}: missing or empty {item['file']}")
    ids = {item["id"] for item in data["components"]}
    for required in ("app", "projectm", "glad", "glm", "hlslparser", "projectm-eval", "stb_image",
                     "angle-ANGLE", "presets", *(f"pack-{pack}" for pack in PACK_IDS)):
        if required not in ids:
            problems.append(f"no entry for {required}")
    commit = engine_commit()
    if commit not in data["lgplNote"]["text"]:
        problems.append(f"the LGPL note does not name the pinned engine commit {commit[:7]}; rerun the script")
    for problem in problems:
        print(problem)
    return 1 if problems else 0


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    if args.check:
        sys.exit(check())
    generate()
