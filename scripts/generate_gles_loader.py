#!/usr/bin/env python3
"""Generate the static OpenGL ES 3.0 load-proc table for ProjectMBridge (tasks T068/T069, T071).

The engine resolves GL entry points through a load proc (`projectm_create_with_opengl_load_proc`).
Contract (projectm-bridge.md) and Constitution I: no `dlsym`. This script reads the iOS SDK's
`OpenGLES/ES3/gl.h`, takes every `GL_API ... GL_APIENTRY glName (...)` declaration, and writes
`Packages/ProjectMBridge/Sources/ProjectMBridge/PMGLESLoader.m`: a table of {name, &function},
sorted by name, and `PMAppleGLESLoadProc`, which looks a name up with bsearch. Every entry is a
public function the app links against in OpenGLES.framework, so nothing is resolved at run time.

Usage:
  python3 scripts/generate_gles_loader.py            # regenerate from the current iOS SDK
  python3 scripts/generate_gles_loader.py --check    # exit 1 if the committed file is stale
Standard library only; needs macOS with Xcode (for the SDK path).
"""
from __future__ import annotations

import argparse
import re
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUTPUT = ROOT / "Packages" / "ProjectMBridge" / "Sources" / "ProjectMBridge" / "PMGLESLoader.m"
DECL = re.compile(r"^GL_API\b[^;]*?\bGL_APIENTRY\s+(gl[A-Za-z0-9_]+)\s*\(", re.M)


def function_names(header_text: str) -> list[str]:
    """Every gl* function declared with GL_API ... GL_APIENTRY, sorted and unique."""
    return sorted(set(DECL.findall(header_text)))


def render(names: list[str], sdk_version: str) -> str:
    rows = "\n".join(f'    {{"{n}", (void *){n}}},' for n in names)
    return f"""// PMGLESLoader.m — GENERATED by scripts/generate_gles_loader.py; do not edit.
// Source: OpenGLES.framework/Headers/ES3/gl.h in the iOS {sdk_version} SDK ({len(names)} functions).
//
// The engine's GL load proc (contract projectm-bridge.md; Constitution I: no dlsym). Every entry is
// a public OpenGL ES 3.0 function linked from OpenGLES.framework; names are sorted for bsearch.
// GLES_SILENCE_DEPRECATION is defined in Package.swift (it must reach the module build).
#import <OpenGLES/ES3/gl.h>
#include <stdlib.h>
#include <string.h>
#import "PMGLESLoader.h"

typedef struct {{
    const char *name;
    void *proc;
}} PMGLEntry;

static const PMGLEntry kPMGLEntries[] = {{
{rows}
}};

static int PMGLEntryCompare(const void *key, const void *element) {{
    return strcmp((const char *)key, ((const PMGLEntry *)element)->name);
}}

void *PMAppleGLESLoadProc(const char *name, void *userData) {{
    (void)userData;
    if (name == NULL) {{
        return NULL;
    }}
    const PMGLEntry *entry = bsearch(name, kPMGLEntries, sizeof(kPMGLEntries) / sizeof(kPMGLEntries[0]),
                                     sizeof(PMGLEntry), PMGLEntryCompare);
    return entry ? entry->proc : NULL;
}}

NSUInteger PMAppleGLESFunctionCount(void) {{
    return sizeof(kPMGLEntries) / sizeof(kPMGLEntries[0]);
}}
"""


def sdk() -> tuple[Path, str]:
    path = subprocess.run(["xcrun", "--sdk", "iphoneos", "--show-sdk-path"], check=True, capture_output=True, text=True).stdout.strip()
    version = subprocess.run(["xcrun", "--sdk", "iphoneos", "--show-sdk-version"], check=True, capture_output=True, text=True).stdout.strip()
    return Path(path), version


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args(argv)
    path, version = sdk()
    header = path / "System/Library/Frameworks/OpenGLES.framework/Headers/ES3/gl.h"
    names = function_names(header.read_text(encoding="utf-8"))
    if len(names) < 200:
        print(f"generate_gles_loader: only {len(names)} functions in {header}", file=sys.stderr)
        return 1
    text = render(names, version)
    if args.check:
        current = OUTPUT.read_text(encoding="utf-8") if OUTPUT.exists() else ""
        # The SDK version line may differ between machines; compare the table only.
        strip = lambda s: re.sub(r"^// Source:.*$", "", s, flags=re.M)
        if strip(current) != strip(text):
            print("generate_gles_loader: PMGLESLoader.m is stale; rerun the script", file=sys.stderr)
            return 1
        print(f"generate_gles_loader: up to date ({len(names)} functions)")
        return 0
    OUTPUT.write_text(text, encoding="utf-8")
    print(f"wrote {OUTPUT.relative_to(ROOT)} ({len(names)} functions, iOS {version} SDK)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
