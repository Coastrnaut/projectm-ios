// AudioProbeSupport.swift — QA-011 Batch 3 (audio): helpers for the audio device tests (B05AudioDeviceTests,
// B05AudioMicDeviceTests). They read the DEBUG probes of Apps/projectM-iOS/Debug/UITestAudioProbes.swift
// (`playbackProbe`, `sessionLog`, `gateProbe`, `importProbe`), tap its panel (`-uitestAudioPanel`), drive real system
// interruptions through SystemUI (Batch 1) and ask the Mac for sound through `MAC-DO` lines that
// scripts/mac_device_driver.py runs (module `audio`; the test then waits on a probe, never on the Mac's log).
import UIKit
import XCTest

extension DeviceAcceptanceCase {
    // MARK: Probes

    func probeValue(_ id: String) -> String {
        let element = app.descendants(matching: .any)[id].firstMatch
        return element.exists ? ((element.value as? String) ?? element.label) : ""
    }

    /// "key=value" tokens of a probe (the first value wins; `sessionLog` entries after " | " are ignored).
    func probeFields(_ id: String) -> [String: String] {
        let head = probeValue(id).components(separatedBy: " | ").first ?? ""
        var fields: [String: String] = [:]
        for token in head.split(separator: " ") {
            guard let eq = token.firstIndex(of: "=") else { continue }
            let key = String(token[..<eq])
            if fields[key] == nil { fields[key] = String(token[token.index(after: eq)...]) }
        }
        return fields
    }

    func probeNumber(_ id: String, _ key: String) -> Double {
        Double(probeFields(id)[key] ?? "") ?? -1
    }

    var playback: [String: String] { probeFields("playbackProbe") }
    func playbackNumber(_ key: String) -> Double { probeNumber("playbackProbe", key) }
    var sourceIndicator: String { app.staticTexts["sourceIndicator"].exists ? app.staticTexts["sourceIndicator"].label : "" }
    var overlayLabel: String { app.descendants(matching: .any)["performanceOverlay"].firstMatch.label }

    /// Reports every numeric field of the playback probe (and the transport position).
    func reportPlayback(_ task: String, _ step: String) {
        var values: [String: Double] = [:]
        for (key, value) in playback { if let number = Double(value) { values[key] = number } }
        report(task, step, values)
    }

    // MARK: Launch

    /// Plays `files` (Documents, generated by `-uitestSeedAudio <seed>`) as In-App Playback from a fresh library, with
    /// the playback probe, the session log and the audio panel; waits until the probe sees delivered audio.
    func launchPlayback(_ task: String, files: [String], seed: String = "ramps", visual: String = "linearSpectrum",
                        settings: [String: Any] = [:], extra: [String] = []) {
        let arguments = ["-uitestResetAudioLibrary", "-uitestSeedAudio", seed,
                         "-uitestImportAudio", files.joined(separator: "|"), "-uitestPlayImported", "YES",
                         "-uitestPlaybackProbe", "-uitestSessionLog", "-uitestAudioPanel", "-uitestSessionEvents"] + extra
        launch(visual: visual, settings: settings, extra: arguments, music: false)
        let delivered = wait(15) { self.playback["state"] == "playing" && self.playbackNumber("buffers") > 20 }
        XCTAssertTrue(delivered, "\(task): \(files.first ?? "") plays and the tap delivers: \(probeValue("playbackProbe"))")
    }

    // MARK: Controls

    func revealControls() {
        let controls = app.otherElements["controls"], area = app.otherElements["visualizerTapArea"].firstMatch
        if controls.exists { return }
        area.tap()
        if !wait(2, { controls.exists }) { area.tap() }
        XCTAssertTrue(wait(5) { controls.exists }, "the controls are shown")
    }

    /// Taps a transport control (shows the controls first; they hide 5 s after the last use).
    func tapTransport(_ id: String) {
        revealControls()
        let button = app.buttons[id]
        XCTAssertTrue(wait(5) { button.exists && button.isHittable }, "\(id) is shown")
        button.tap()
    }

    /// Taps a button of the DEBUG audio panel or the session-event panel.
    func tapPanel(_ id: String) {
        let button = app.buttons[id].firstMatch
        XCTAssertTrue(wait(5) { button.exists }, "panel button \(id)")
        if button.exists { button.tap() }
    }

    func waitForIndicator(_ suffix: String, _ seconds: Double = 10) -> Bool {
        wait(seconds) { self.sourceIndicator.hasSuffix(suffix) }
    }

    // MARK: Mac side

    /// Asks the Mac driver to act (`MAC-DO {json}`); returns the action's id. The Mac answers in its own log; the test
    /// waits on a probe instead.
    @discardableResult
    func macDo(_ module: String, _ action: String, _ parameters: [String: Any] = [:]) -> String {
        let id = "\(name.split(separator: " ").last?.trimmingCharacters(in: CharacterSet(charactersIn: "]")) ?? "test")-\(Int(Date().timeIntervalSince1970 * 1000) % 1_000_000)"
        // scripts/mac_device_driver.py dispatches "<module>.<verb>" (Batch 1's MacDriver) and plays `file` from the repo.
        var body: [String: Any] = ["id": id, "action": "\(module).\(action)", "device": deviceModel()]
        for (key, value) in parameters { body[key] = value }
        if let fixture = body.removeValue(forKey: "fixture") as? String { body["file"] = "Build/fixtures/\(fixture)" }
        if let data = try? JSONSerialization.data(withJSONObject: body, options: [.sortedKeys]),
           let line = String(data: data, encoding: .utf8) {
            print("MAC-DO \(line)")
        }
        return id
    }

    /// The Mac plays the music fixture on its speaker for `seconds` (looped); for microphone tests next to the device.
    func macPlayMusic(seconds: Int) {
        macDo("audio", "play", ["fixture": "music-fixture.m4a", "seconds": seconds, "loop": true])
    }

    func macStopAudio() {
        macDo("audio", "stop")
    }

    // MARK: Interruptions

    enum RealInterruption: String { case clockTimer, siri }

    /// Interruption counts from `sessionLog`: began, ended, resume.
    func sessionCounts() -> (began: Int, ended: Int, resume: Int) {
        let f = probeFields("sessionLog")
        return (Int(f["began"] ?? "") ?? 0, Int(f["ended"] ?? "") ?? 0, Int(f["resume"] ?? "") ?? 0)
    }

    /// Triggers a real system interruption and checks the app's state against the AUD-014 policy for what iOS
    /// delivered: a playing track with "should resume" continues by itself; without it, it holds ("Interrupted") and
    /// Play continues at the held position; a user pause stays paused. Returns what happened, for the report.
    @discardableResult
    func realInterruption(_ task: String, _ kind: RealInterruption, whilePaused: Bool, ramp: Bool = true) -> [String: Double] {
        let before = sessionCounts()
        switch kind {
        case .clockTimer: SystemUI(app: app).startClockTimer(seconds: 5)
        case .siri: SystemUI(app: app).siriInterruption()
        }
        let began = wait(25) { self.sessionCounts().began > before.began }
        let ended = wait(20) { self.sessionCounts().ended > before.ended }
        if app.state != .runningForeground { app.activate(); _ = wait(10) { self.app.state == .runningForeground } }
        pause(2)
        let after = sessionCounts()
        let resumeHint = after.resume > before.resume
        var result: [String: Double] = ["began": began ? 1 : 0, "ended": ended ? 1 : 0, "shouldResume": resumeHint ? 1 : 0,
                                        "paused": whilePaused ? 1 : 0]
        let label = "\(kind.rawValue) \(whilePaused ? "paused" : "playing")"
        XCTAssertTrue(began, "\(task) \(label): iOS delivered an interruption to the app: \(probeValue("sessionLog").suffix(300))")
        if whilePaused {
            let stayed = waitForIndicator("· Paused", 5)
            result["stayedPaused"] = stayed ? 1 : 0
            XCTAssertTrue(stayed, "\(task) \(label): a user pause stays paused: \(sourceIndicator)")
        } else if resumeHint {
            let resumed = waitForIndicator("· Active audio", 10)
            result["autoResumed"] = resumed ? 1 : 0
            XCTAssertTrue(resumed, "\(task) \(label): with shouldResume the track continues: \(sourceIndicator)")
        } else {
            let held = sourceIndicator.hasSuffix("· Interrupted") || sourceIndicator.hasSuffix("· Paused")
            result["held"] = held ? 1 : 0
            XCTAssertTrue(held, "\(task) \(label): without shouldResume playback holds: \(sourceIndicator)")
        }
        if !sourceIndicator.hasSuffix("· Active audio") {
            tapTransport("transportPlayPause")
            let playing = waitForIndicator("· Active audio", 10)
            result["playResumes"] = playing ? 1 : 0
            XCTAssertTrue(playing, "\(task) \(label): Play continues: \(sourceIndicator)")
            if ramp {
                pause(1)
                result["cutJumpMs"] = playbackNumber("cutJumpMs")
                XCTAssertLessThan(abs(playbackNumber("cutJumpMs")), 300,
                                  "\(task) \(label): it continues at the held position: \(probeValue("playbackProbe"))")
            }
        }
        report(task, label, result)
        return result
    }

    /// The synthetic lost output route (headphones unplugged): pauses with the route reason; Play continues.
    func routeLostThenPlay(_ task: String) {
        tapPanel("session:routeLost")
        let paused = waitForIndicator("· Paused", 5)
        XCTAssertTrue(paused, "\(task) route lost: paused: \(sourceIndicator)")
        tapTransport("transportPlayPause")
        let playing = waitForIndicator("· Active audio", 10)
        XCTAssertTrue(playing, "\(task) route lost: Play continues: \(sourceIndicator)")
        report(task, "route lost then Play", ["paused": paused ? 1 : 0, "playResumes": playing ? 1 : 0])
    }

    // MARK: Screen motion

    /// The largest whole-screen motion over three pairs of screenshots 1 s apart.
    func peakMotion(_ task: String, _ label: String) -> Double {
        var values: [Double] = []
        for i in 0..<3 {
            let (_, a) = screen(task, "\(label) \(i) a")
            pause(1)
            let (_, b) = screen(task, "\(label) \(i) b")
            values.append(Self.change(a, b))
        }
        let peak = values.max() ?? 0
        report(task, label, ["motionPeak": peak])
        return peak
    }

    /// `On My iPhone` / `On My iPad`: the Files location that holds the app's Documents (UIFileSharingEnabled).
    var onMyDevice: String { UIDevice.current.userInterfaceIdiom == .pad ? "On My iPad" : "On My iPhone" }
}
