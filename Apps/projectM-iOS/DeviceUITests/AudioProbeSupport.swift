// AudioProbeSupport.swift — QA-011 Batch 3 (audio): helpers for the audio device tests (B05AudioDeviceTests,
// B05AudioMicDeviceTests). They read the DEBUG probes of Apps/projectM-iOS/Debug/UITestAudioProbes.swift
// (`playbackProbe`, `sessionLog`, `gateProbe`, `importProbe`), tap its panel (`-uitestAudioPanel`), drive real system
// interruptions through SystemUI (Batch 1) and ask the Mac for sound through `MAC-DO` lines that
// scripts/mac_device_driver.py runs (module `audio`; the test then waits on a probe, never on the Mac's log).
import UIKit
import XCTest

extension DeviceAcceptanceCase {
    // MARK: Probes

    func probeValue(_ id: String) -> String {
        let element = app.descendants(matching: .any)[id].firstMatch
        return element.exists ? ((element.value as? String) ?? element.label) : ""
    }

    /// "key=value" tokens of a probe (the first value wins; `sessionLog` entries after " | " are ignored).
    func probeFields(_ id: String) -> [String: String] {
        let head = probeValue(id).components(separatedBy: " | ").first ?? ""
        var fields: [String: String] = [:]
        for token in head.split(separator: " ") {
            guard let eq = token.firstIndex(of: "=") else { continue }
            let key = String(token[..<eq])
            if fields[key] == nil { fields[key] = String(token[token.index(after: eq)...]) }
        }
        return fields
    }

    func probeNumber(_ id: String, _ key: String) -> Double {
        Double(probeFields(id)[key] ?? "") ?? -1
    }

    var playback: [String: String] { probeFields("playbackProbe") }
    func playbackNumber(_ key: String) -> Double { probeNumber("playbackProbe", key) }
    var sourceIndicator: String { app.staticTexts["sourceIndicator"].exists ? app.staticTexts["sourceIndicator"].label : "" }
    var overlayLabel: String { app.descendants(matching: .any)["performanceOverlay"].firstMatch.label }

    /// Reports every numeric field of the playback probe (and the transport position).
    func reportPlayback(_ task: String, _ step: String) {
        var values: [String: Double] = [:]
        for (key, value) in playback { if let number = Double(value) { values[key] = number } }
        report(task, step, values)
        print("DEVICE-ACCEPT-NOTE \(task) \(step) playbackProbe: \(probeValue("playbackProbe"))")   // changes=, undecoded=
    }

    // MARK: Launch

    /// Plays `files` (Documents, generated by `-uitestSeedAudio <seed>`) as In-App Playback from a fresh library, with
    /// the playback probe, the session log and the audio panel; waits until the probe sees delivered audio.
    func launchPlayback(_ task: String, files: [String], seed: String = "ramps", visual: String = "linearSpectrum",
                        settings: [String: Any] = [:], extra: [String] = [], panels: Bool = true) {
        // `panels: false` leaves out the DEBUG audio and session-event panels (buttons the test taps): at AX5 the
        // audio panel (from 250 pt down, about 110 pt tall) lies over the transport's buttons (AUD-006-T41).
        let arguments = ["-uitestResetAudioLibrary", "-uitestSeedAudio", seed,
                         "-uitestImportAudio", files.joined(separator: "|"), "-uitestPlayImported", "YES",
                         "-uitestPlaybackProbe", "-uitestSessionLog"]
            + (panels ? ["-uitestAudioPanel", "-uitestSessionEvents"] : []) + extra
        launch(visual: visual, settings: settings, extra: arguments, music: false)
        let delivered = wait(15) { self.playback["state"] == "playing" && self.playbackNumber("buffers") > 20 }
        XCTAssertTrue(delivered, "\(task): \(files.first ?? "") plays and the tap delivers: \(probeValue("playbackProbe"))")
    }

    // MARK: Controls

    /// Shows the controls. Controls that still exist but are fading out (they hide 5 s after the last use) are let go
    /// first and shown fresh: on D3 (2026-11-18) `controls` existed when checked and was gone when its buttons were
    /// tapped, so the transport checks after a quiet moment failed. The taps land below the probe readouts
    /// (`tapVisualizer`): on D1 (r16, 2026-11-24) `visualizerTapArea.tap()` hit the top-left corner and did nothing.
    func revealControls() {
        let controls = app.otherElements["controls"]
        let anchor = app.buttons["transportPlayPause"]
        if controls.exists, anchor.exists, anchor.isHittable { return }
        if controls.exists { _ = wait(8) { !controls.exists } }
        tapVisualizer(attempt: 0)
        if !wait(2, { controls.exists }) { tapVisualizer(attempt: 1) }
        XCTAssertTrue(wait(5) { controls.exists }, "the controls are shown")
    }

    /// Taps a transport control (shows the controls first; they hide 5 s after the last use).
    func tapTransport(_ id: String) {
        revealControls()
        let button = app.buttons[id]
        XCTAssertTrue(wait(5) { button.exists && button.isHittable }, "\(id) is shown")
        button.tap()
    }

    /// Taps a button of the DEBUG audio panel or the session-event panel.
    func tapPanel(_ id: String) {
        let button = app.buttons[id].firstMatch
        XCTAssertTrue(wait(5) { button.exists }, "panel button \(id)")
        if button.exists { button.tap() }
    }

    func waitForIndicator(_ suffix: String, _ seconds: Double = 10) -> Bool {
        wait(seconds) { self.sourceIndicator.hasSuffix(suffix) }
    }

    // MARK: Mac side

    /// Asks the Mac driver to act (`MAC-DO {json}`); returns the action's id. The Mac answers in its own log; the test
    /// waits on a probe instead.
    @discardableResult
    func macDo(_ module: String, _ action: String, _ parameters: [String: Any] = [:]) -> String {
        let id = "\(name.split(separator: " ").last?.trimmingCharacters(in: CharacterSet(charactersIn: "]")) ?? "test")-\(Int(Date().timeIntervalSince1970 * 1000) % 1_000_000)"
        // scripts/mac_device_driver.py dispatches "<module>.<verb>" (Batch 1's MacDriver) and plays `file` from the repo.
        var body: [String: Any] = ["id": id, "action": "\(module).\(action)", "device": deviceModel()]
        for (key, value) in parameters { body[key] = value }
        if let fixture = body.removeValue(forKey: "fixture") as? String { body["file"] = "Build/fixtures/\(fixture)" }
        if let data = try? JSONSerialization.data(withJSONObject: body, options: [.sortedKeys]),
           let line = String(data: data, encoding: .utf8) {
            print("MAC-DO \(line)")
        }
        return id
    }

    /// The Mac plays the music fixture on its speaker for `seconds` (looped); for microphone tests next to the device.
    func macPlayMusic(seconds: Int) {
        macDo("audio", "play", ["fixture": "music-fixture.m4a", "seconds": seconds, "loop": true])
    }

    func macStopAudio() {
        macDo("audio", "stop")
    }

    // MARK: Interruptions

    enum RealInterruption: String { case clockTimer, siri }

    /// Interruption counts from `sessionLog`: began, ended, resume.
    func sessionCounts() -> (began: Int, ended: Int, resume: Int) {
        let f = probeFields("sessionLog")
        return (Int(f["began"] ?? "") ?? 0, Int(f["ended"] ?? "") ?? 0, Int(f["resume"] ?? "") ?? 0)
    }

    /// Triggers a real system interruption and checks the app's state against the AUD-014 policy for what iOS
    /// delivered: a playing track with "should resume" continues by itself; without it, it holds ("Interrupted") and
    /// Play continues at the held position; a user pause stays paused. Returns what happened, for the report.
    @discardableResult
    func realInterruption(_ task: String, _ kind: RealInterruption, whilePaused: Bool, ramp: Bool = true) -> [String: Double] {
        let before = sessionCounts()
        switch kind {
        case .clockTimer: SystemUI(app: app).startClockTimer(seconds: 5)
        case .siri:
            SiriAvailability.unavailableSeen = false
            SystemUI(app: app).siriInterruption()
            if SiriAvailability.unavailableSeen {   // Siri is off on this device: this step cannot run
                let step = "\(task) siri \(whilePaused ? "paused" : "playing")"
                SiriAvailability.skippedSteps.append(step)
                print("DEVICE-ACCEPT-NOTE \(step): Siri is off on \(deviceModel()); the Siri interruption was not run")
                report(task, "siri \(whilePaused ? "paused" : "playing")", ["siriUnavailable": 1])
                return ["siriUnavailable": 1]
            }
        }
        let began = wait(25) { self.sessionCounts().began > before.began }
        // A typed Siri request answers silently and never takes the audio session, so iOS sends no interruption
        // (D2, iPadOS 27.2, 2026-11-21: began stayed at the clock timer's count in AUD-006 and AUD-014). That is a
        // correct outcome, not a failure: the app must simply be undisturbed. The alarm (clock timer) covers the
        // interruption path in both tests (AUD-006-T40: "an incoming call or alarm").
        if kind == .siri && !began {
            if app.state != .runningForeground { app.activate(); _ = wait(10) { self.app.state == .runningForeground } }
            let label = "siri \(whilePaused ? "paused" : "playing")"
            let expected = whilePaused ? "· Paused" : "· Active audio"
            let undisturbed = waitForIndicator(expected, 5)
            print("DEVICE-ACCEPT-NOTE \(task) \(label): Siri answered without an audio interruption; the app stays "
                  + "\(whilePaused ? "paused" : "playing"): \(sourceIndicator)")
            let result: [String: Double] = ["began": 0, "siriInterrupted": 0, "undisturbed": undisturbed ? 1 : 0,
                                            "paused": whilePaused ? 1 : 0]
            report(task, label, result)
            XCTAssertTrue(undisturbed, "\(task) \(label): no interruption arrived, so the app is undisturbed: \(sourceIndicator)")
            return result
        }
        // A ringing timer holds its interruption until someone stops it (D3 pass 3, 2026-11-19: no `ended` in seven
        // runs, and its banner covered the session panel afterwards), so the test stops it as a person would.
        if kind == .clockTimer, began { pause(2); SystemUI(app: app).stopClockTimer() }
        let ended = wait(20) { self.sessionCounts().ended > before.ended }
        if app.state != .runningForeground { app.activate(); _ = wait(10) { self.app.state == .runningForeground } }
        pause(2)
        let after = sessionCounts()
        let resumeHint = after.resume > before.resume
        var result: [String: Double] = ["began": began ? 1 : 0, "ended": ended ? 1 : 0, "shouldResume": resumeHint ? 1 : 0,
                                        "paused": whilePaused ? 1 : 0]
        let label = "\(kind.rawValue) \(whilePaused ? "paused" : "playing")"
        XCTAssertTrue(began, "\(task) \(label): iOS delivered an interruption to the app: \(probeValue("sessionLog").suffix(300))")
        if sourceIndicator.hasPrefix("Microphone") {
            // The microphone has no transport and no pause (FR-051, InterruptionPolicy): with shouldResume it runs
            // again by itself, "Active audio" with sound and "Audio received — silent" in a quiet room; without it,
            // it shows "Interrupted". QA-011 full 8 and pass 9 (D2, 2026-11-19): the old check waited for "Active
            // audio" and then looked for the In-App Playback transport, which Microphone mode does not have.
            let running = { self.sourceIndicator.hasSuffix("· Active audio") || self.sourceIndicator.contains("· Audio received") }
            if resumeHint {
                let resumed = wait(10, running)
                result["autoResumed"] = resumed ? 1 : 0
                XCTAssertTrue(resumed, "\(task) \(label): with shouldResume the microphone runs again: \(sourceIndicator)")
            } else {
                let held = waitForIndicator("· Interrupted", 5)
                result["held"] = held ? 1 : 0
                XCTAssertTrue(held, "\(task) \(label): without shouldResume the microphone shows Interrupted: \(sourceIndicator)")
            }
            report(task, label, result)
            return result
        }
        if whilePaused {
            let stayed = waitForIndicator("· Paused", 5)
            result["stayedPaused"] = stayed ? 1 : 0
            XCTAssertTrue(stayed, "\(task) \(label): a user pause stays paused: \(sourceIndicator)")
        } else if resumeHint {
            let resumed = waitForIndicator("· Active audio", 10)
            result["autoResumed"] = resumed ? 1 : 0
            XCTAssertTrue(resumed, "\(task) \(label): with shouldResume the track continues: \(sourceIndicator)")
        } else {
            let held = sourceIndicator.hasSuffix("· Interrupted") || sourceIndicator.hasSuffix("· Paused")
            result["held"] = held ? 1 : 0
            XCTAssertTrue(held, "\(task) \(label): without shouldResume playback holds: \(sourceIndicator)")
        }
        if !sourceIndicator.hasSuffix("· Active audio") {
            tapTransport("transportPlayPause")
            let playing = waitForIndicator("· Active audio", 10)
            result["playResumes"] = playing ? 1 : 0
            XCTAssertTrue(playing, "\(task) \(label): Play continues: \(sourceIndicator)")
            if ramp {
                pause(1)
                result["cutJumpMs"] = playbackNumber("cutJumpMs")
                XCTAssertLessThan(abs(playbackNumber("cutJumpMs")), 300,
                                  "\(task) \(label): it continues at the held position: \(probeValue("playbackProbe"))")
            }
        }
        report(task, label, result)
        return result
    }

    /// The synthetic lost output route (headphones unplugged): pauses with the route reason; Play continues.
    ///
    /// The session panel sits at the top edge, in the status-bar band; on D3 (iPadOS 26.5, 2026-11-18) the tap on
    /// `session:routeLost` (x 483-605, y 6-31) changed nothing: playback went on. The tap is confirmed by the
    /// session log's route count and repeated once at the button's lower edge.
    func routeLostThenPlay(_ task: String) {
        let routesBefore = Int(probeFields("sessionLog")["routes"] ?? "") ?? -1
        tapPanel("session:routeLost")
        if routesBefore >= 0, !wait(2, { (Int(self.probeFields("sessionLog")["routes"] ?? "") ?? -1) > routesBefore }) {
            let button = app.buttons["session:routeLost"].firstMatch
            print("DEVICE-ACCEPT-NOTE \(task) route lost: the first tap posted nothing (\(button.frame)); tapping its lower edge")
            button.coordinate(withNormalizedOffset: CGVector(dx: 0.5, dy: 0.92)).tap()
        }
        let paused = waitForIndicator("· Paused", 5)
        XCTAssertTrue(paused, "\(task) route lost: paused: \(sourceIndicator)")
        tapTransport("transportPlayPause")
        let playing = waitForIndicator("· Active audio", 10)
        XCTAssertTrue(playing, "\(task) route lost: Play continues: \(sourceIndicator)")
        report(task, "route lost then Play", ["paused": paused ? 1 : 0, "playResumes": playing ? 1 : 0])
    }

    // MARK: Screen motion

    /// The largest whole-screen motion over three pairs of screenshots 1 s apart.
    func peakMotion(_ task: String, _ label: String) -> Double {
        var values: [Double] = []
        for i in 0..<3 {
            let (_, a) = screen(task, "\(label) \(i) a")
            pause(1)
            let (_, b) = screen(task, "\(label) \(i) b")
            values.append(Self.change(a, b))
        }
        let peak = values.max() ?? 0
        report(task, label, ["motionPeak": peak])
        return peak
    }

    /// `On My iPhone` / `On My iPad`: the Files location that holds the app's Documents (UIFileSharingEnabled).
    var onMyDevice: String { UIDevice.current.userInterfaceIdiom == .pad ? "On My iPad" : "On My iPhone" }

    /// Picks `name` from the app's own Documents in the Files picker the app presents.
    ///
    /// The picker does not list the presenting app's own folder under On My iPhone/iPad (QA-011 device run
    /// 2026-11-18: D1, D2 and D3 listed the other apps' folders and no projectM, although the installed build has
    /// UIFileSharingEnabled and LSSupportsOpeningDocumentsInPlace). So the test host opens the picker in its Documents
    /// (`-uitestPickerInDocuments`, DEBUG: `fileDialogDefaultDirectory`) and the file is tapped there; only when it is
    /// not shown does this fall back to browsing On My … › projectM (which then fails, naming what is missing).
    ///
    /// QA-011 pass 3 (D2, D3 2026-11-19): the picker did open in Documents, but its grid labels a file
    /// "<stem>, <extension>, <date>, <size>" and lists most fixtures below the first screen, so the old
    /// "label BEGINSWITH <name>" wait never matched; SystemUI's `findFile` matches that label and scrolls the grid.
    @discardableResult
    func pickFromAppDocuments(_ name: String) -> Bool {
        let system = SystemUI(app: app)
        // QA-011 pass 6 (D2, 2026-11-19, fresh reinstall): the picker opened in On My iPad instead, and searching that
        // grid for the file scrolled the projectM folder away. When the app's folder is shown, go into it first.
        system.enterAppFolderIfShown()
        if system.findFile(name, initialWait: 8, swipes: 8) {
            system.tapFile(name)   // taps again when the first tap selected nothing (rerun 3, D3)
            return true
        }
        print("DEVICE-ACCEPT-NOTE \(name) is not where the picker opened; browsing \(onMyDevice) > \(SystemUI.appDisplayName)")
        return system.filesPick(path: [onMyDevice, SystemUI.appDisplayName], name: name)
    }
}

/// Whether XCUITest could reach Siri. With Siri off, `XCUIDevice.siriService.activate` records an issue instead of
/// throwing: "Unable to activate Siri because it is not enabled on this device" (D3, 2026-11-18) or, after a 60 s
/// wait, "Timed out waiting for Siri to activate" (D3 iPadOS 26.5, QA-011 pass 3, 2026-11-19). The test classes that
/// use Siri pass every issue through `SiriAvailability.swallow` in `record(_:)`: either issue sets `unavailableSeen`
/// (and `knownUnavailable` for the rest of the run, so later Siri steps skip at once instead of waiting another 60 s)
/// and is not recorded, and the test skips its Siri steps with `skipReason` instead of failing.
enum SiriAvailability {
    nonisolated(unsafe) static var unavailableSeen = false
    /// Siri steps run only when the run asks for them (`TEST_RUNNER_SIRI=1`, its own batch): on D3 (2026-11-19) a Siri
    /// request whose window never loaded accessibility was followed by "Timed out while enabling automation mode" for
    /// every later test launch, which left the device unable to run UI tests until a person reset it.
    nonisolated(unsafe) static var knownUnavailable = ProcessInfo.processInfo.environment["SIRI"] != "1"
    nonisolated(unsafe) static var skippedSteps: [String] = []

    /// True when `issue` is XCUITest's "Siri is not enabled" or "Timed out waiting for Siri to activate" (the caller
    /// then does not record it).
    static func swallow(_ issue: XCTIssue) -> Bool {
        let text = issue.compactDescription
        let siri = text.contains("Siri") || text.contains("com.apple.siri")
        guard siri, text.contains("not enabled") || text.contains("Timed out waiting for Siri")
            || text.contains("has not loaded accessibility") else {
            return false
        }
        unavailableSeen = true
        knownUnavailable = true
        return true
    }

    static let skipReason = "Siri is off or unreachable on this device (XCUITest: \"Unable to activate Siri because it "
        + "is not enabled\", \"Timed out waiting for Siri to activate\", or Siri's window never loaded accessibility), "
        + "or the run did not ask for Siri: run the Siri steps in their own batch with SIRI=1 and Siri on"
}
