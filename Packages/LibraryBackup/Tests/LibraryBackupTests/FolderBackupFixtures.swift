// FolderBackupFixtures.swift — FILE-006: a fixture library with media (a 4 MiB fake video payload, a photo
// payload, a legacy photo copy, an audio asset and the audio index) and a file access that counts the
// bytes read from each file (research FILE-006-D7).
import Foundation
import LocalPortability
import XCTest
@testable import LibraryBackup

/// Counts bytes read and copies per source path, around the real file access.
final class CountingFileAccess: BackupFileAccess, @unchecked Sendable {
    private let lock = NSLock()
    private let base = LocalBackupFileAccess()
    private var read: [String: Int64] = [:]
    private var copies: [String] = []
    /// Tests only: thrown before the copy of a source whose file name contains this text.
    var failCopy: String?

    func status(of url: URL, includingDate: Bool) -> BackupFileStatus? { base.status(of: url, includingDate: includingDate) }

    func digest(of url: URL) throws -> BackupDigest {
        let digest = try base.digest(of: url)
        record(url, digest.byteCount, copy: false)
        return digest
    }

    func copy(from source: URL, to destination: URL) throws -> BackupDigest {
        if let failCopy, source.lastPathComponent.contains(failCopy) { throw CocoaError(.fileReadUnknown) }
        let digest = try base.copy(from: source, to: destination)
        record(source, digest.byteCount, copy: true)
        return digest
    }

    private func record(_ url: URL, _ bytes: Int64, copy: Bool) {
        lock.lock()
        defer { lock.unlock() }
        read[url.standardizedFileURL.path, default: 0] += bytes
        if copy { copies.append(url.lastPathComponent) }
    }

    func bytesRead(_ url: URL) -> Int64 {
        lock.lock()
        defer { lock.unlock() }
        return read[url.standardizedFileURL.path] ?? 0
    }

    var totalBytesRead: Int64 {
        lock.lock()
        defer { lock.unlock() }
        return read.values.reduce(0, +)
    }

    var copied: [String] {
        lock.lock()
        defer { lock.unlock() }
        return copies
    }

    func reset() {
        lock.lock()
        defer { lock.unlock() }
        read = [:]
        copies = []
    }
}

struct MediaLibraryFixture {
    /// 4 MiB with CryptoKit; 256 KiB where SHA-256 is the portable Swift hasher (Linux CI, debug builds),
    /// which keeps the package suite under a minute there (owner rule 7).
    #if canImport(CryptoKit) && !LIBRARYBACKUP_NO_CRYPTOKIT
    static let videoBytes = 4 << 20
    #else
    static let videoBytes = 256 << 10
    #endif
    static let video = UUID(uuidString: "0B000000-0000-4000-8000-0000000000F6")!
    static let photo = UUID(uuidString: "0A000000-0000-4000-8000-0000000000F6")!
    static let legacyPhoto = UUID(uuidString: "0A000000-0000-4000-8000-0000000000F7")!

    let root: URL
    let destination: URL

    var photos: ContentAddressedMediaFolder {
        ContentAddressedMediaFolder(directory: MediaBackupInventory.photosFolder(root), extensions: LibraryErasePolicy.photoExtensions)
    }
    var videos: ContentAddressedMediaFolder {
        ContentAddressedMediaFolder(directory: MediaBackupInventory.videosFolder(root), extensions: LibraryErasePolicy.videoExtensions)
    }
    var videoURL: URL { videos.resolve(Self.video)! }
    var legacyPhotoURL: URL { photos.resolve(Self.legacyPhoto)! }
    var audioAssets: URL { MediaBackupInventory.audioFolder(root).appendingPathComponent("assets", isDirectory: true) }
    var audioIndex: URL { MediaBackupInventory.audioFolder(root).appendingPathComponent("index.json", isDirectory: false) }
    var backupFolder: URL { BackupFolderLayout.backupFolder(in: destination) }
    var media: URL { backupFolder.appendingPathComponent("media", isDirectory: true) }

    static func make(_ test: XCTestCase, _ label: String) throws -> MediaLibraryFixture {
        let base = FileManager.default.temporaryDirectory.appendingPathComponent("FolderBackup-\(label)-\(UUID().uuidString)", isDirectory: true)
        let fixture = MediaLibraryFixture(root: base.appendingPathComponent("library", isDirectory: true),
                                          destination: base.appendingPathComponent("drive", isDirectory: true))
        test.addTeardownBlock { try? FileManager.default.removeItem(at: base) }
        let files = FileManager.default
        let scratch = base.appendingPathComponent("scratch", isDirectory: true)
        for url in [fixture.photos.directory, fixture.videos.directory, fixture.audioAssets, scratch, fixture.destination] {
            try files.createDirectory(at: url, withIntermediateDirectories: true)
        }
        // The video payload: 4 MiB of generated bytes, not a real movie.
        var video = Data(count: videoBytes)
        video.withUnsafeMutableBytes { (raw: UnsafeMutableRawBufferPointer) in
            for index in 0..<raw.count { raw[index] = UInt8(truncatingIfNeeded: index &* 31 &+ index >> 9) }
        }
        try intern(video, id: Self.video, ext: "mov", into: fixture.videos, scratch: scratch)
        try intern(BackupFixtures.png(6), id: Self.photo, ext: "png", into: fixture.photos, scratch: scratch)
        try BackupFixtures.png(7).write(to: fixture.photos.payloadURL(Self.legacyPhoto.uuidString + ".png"))   // a legacy copy
        let track = Data("fake-audio-track".utf8) + Data(repeating: 0x41, count: 20_000)
        try track.write(to: fixture.audioAssets.appendingPathComponent(PortableSHA256.hex(track) + ".m4a"))
        try Data(#"{"schemaVersion":1,"tracks":[]}"#.utf8).write(to: fixture.audioIndex)
        return fixture
    }

    private static func intern(_ bytes: Data, id: UUID, ext: String, into folder: ContentAddressedMediaFolder, scratch: URL) throws {
        let source = scratch.appendingPathComponent(id.uuidString + "." + ext)
        try bytes.write(to: source)
        _ = try folder.intern(source, as: id, consumingSource: true)
    }

    /// One folder backup with a small archive.
    @discardableResult
    func backUp(_ access: any BackupFileAccess, fault: (@Sendable (FolderBackupStep, String) throws -> Void)? = nil) throws -> FolderBackupReport {
        try FolderBackupWriter(access: access, fault: fault).write(archive: Data("archive".utf8), assets: MediaBackupInventory.assets(root: root),
                                                                   to: backupFolder, appVersion: "1.2 (3)", createdAt: BackupFixtures.now)
    }

    /// Every file name in the backup's media folder.
    func mediaNames() -> [String] { ((try? FileManager.default.contentsOfDirectory(atPath: media.path)) ?? []).sorted() }

    /// The manifest names only files that exist with the recorded size and hash.
    func assertManifestConsistent(file: StaticString = #filePath, line: UInt = #line) {
        guard let manifest = BackupFolderManifest.read(folder: backupFolder) else { return XCTFail("no manifest", file: file, line: line) }
        let access = LocalBackupFileAccess()
        for entry in manifest.assets {
            let url = backupFolder.appendingPathComponent(entry.location)
            let digest = try? access.digest(of: url)
            XCTAssertEqual(digest?.sha256, entry.sha256, entry.name, file: file, line: line)
            XCTAssertEqual(digest?.byteCount, entry.byteCount, entry.name, file: file, line: line)
        }
    }
}
